(** The whole-table certificate, in the shared checker's raw [forallb] shape
    ([window_disc_nonres_check_fn], [window_disc.v]): one [vm_compute] field
    multiplication per entry. *)
Lemma nonres_check_true :
  List.forallb
    (fun i => List.forallb
       (window_disc_nonres_check_fn vcv_table vcv_default nonres_root_table i)
       (List.seq 0 8))
    (List.seq 0 22) = true.
Proof. vm_cast_no_check (@eq_refl bool true). Qed.

(** Every window/digit of the ValueCommitV short table has a non-square
    discriminant.  Digit as a plain [Z] in [[0, 8)]. *)
Lemma window_disc_qr_value_commit_v_all_Z
    (w : nat) (digit : Z) (Hw : (w < 22)%nat) (Hdig : 0 <= digit < 8) :
  is_square (window_disc (List.nth w vcv_table vcv_default) digit) = false.
Proof.
  exact (window_disc_nonres_entry_Z _ _ _ _ nonres_check_true w digit Hw Hdig).
Qed.
