(** The whole-table certificate, in the shared checker's raw [forallb] shape
    ([window_disc_nonres_check_fn], [window_disc.v]): one [vm_compute] field
    multiplication per entry. *)
Lemma nonres_check_true :
  List.forallb
    (fun i => List.forallb
       (window_disc_nonres_check_fn sag_table sag_default nonres_root_table i)
       (List.seq 0 8))
    (List.seq 0 85) = true.
Proof. vm_cast_no_check (@eq_refl bool true). Qed.

(** Every window/digit of the SpendAuthG table has a non-square discriminant.
    Digit form as [Z.of_nat d], [d < 8]. *)
Lemma window_disc_qr_spend_auth_g_all
    (w d : nat) (Hw : (w < 85)%nat) (Hd : (d < 8)%nat) :
  is_square (window_disc (List.nth w sag_table sag_default) (Z.of_nat d)) = false.
Proof.
  exact (window_disc_nonres_entry _ _ _ _ nonres_check_true w d Hw Hd).
Qed.

(** [Z]-digit convenience form: for any [digit] in [[0, 8)] as a plain [Z]. *)
Lemma window_disc_qr_spend_auth_g_all_Z
    (w : nat) (digit : Z) (Hw : (w < 85)%nat) (Hdig : 0 <= digit < 8) :
  is_square (window_disc (List.nth w sag_table sag_default) digit) = false.
